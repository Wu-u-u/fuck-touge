export interface ThemeChoice {
  label: string;
  dark: string;
  light: string;
}

// 可选主题：每套都有深/浅变体，跟随平台显示模式自动切换
export const THEME_CHOICES: Record<ThemeName, ThemeChoice> = {
  catppuccin: { label: "Catppuccin", dark: "catppuccin-mocha", light: "catppuccin-latte" },
  github: { label: "GitHub 高对比", dark: "github-hc-dark", light: "github-hc-light" },
};

/** 未知主题名回退到默认 Catppuccin */
export const normalizeThemeName = (name: unknown): ThemeName =>
  name === "github" ? "github" : "catppuccin";

/** 按平台请求的主题名映射到对应深/浅变体 */
export const uiTheme = (platformName: string, themeName: ThemeName): string => {
  const t = THEME_CHOICES[themeName] || THEME_CHOICES.catppuccin;
  return platformName === "vs" ? t.light : platformName === "vs-dark" ? t.dark : platformName;
};
